"""Contract between results/results.json and the thesis text (docs/THESIS_KEYS.txt).

Gate G5 passes only when this file passes:

    python -m pytest -q tests/test_results_contract.py

Do not edit this file; if a key cannot be produced, store null and explain it in the top-level notes list.
"""
import json
import math
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "results.json"
KEYS_FILE = ROOT / "docs" / "THESIS_KEYS.txt"
MISSING = object()


def lookup(tree, key):
    """Value at a dotted key.

    Some identifiers contain dots themselves (PPO configurations such as R2_l10_d0.5_lr3e-4) and are stored as
    one JSON key, so at every level the longest run of parts that exists as one key wins. The thesis builder
    reads results.json with the same rule.
    """
    parts, node, i = key.split("."), tree, 0
    while i < len(parts):
        if not isinstance(node, dict):
            return MISSING
        for j in range(len(parts), i, -1):
            cand = ".".join(parts[i:j])
            if cand in node:
                node, i = node[cand], j
                break
        else:
            return MISSING
    return node


def thesis_keys():
    return [k.strip() for k in KEYS_FILE.read_text(encoding="utf-8").splitlines() if k.strip()]


@pytest.fixture(scope="module")
def results():
    assert RESULTS.exists(), f"{RESULTS} not found"
    return json.loads(RESULTS.read_text(encoding="utf-8"))


def test_every_thesis_key_present(results):
    missing = [k for k in thesis_keys() if lookup(results, k) is MISSING]
    assert not missing, f"{len(missing)} thesis keys are missing from results.json, for example: {missing[:25]}"


def test_null_keys_are_explained(results):
    keys = thesis_keys()
    nulls = [k for k in keys if lookup(results, k) is None]
    if nulls:
        print(f"\n{len(nulls)} thesis keys hold null:\n  " + "\n  ".join(nulls))
    notes = [str(n) for n in (results.get("notes") or [])]

    def explained(key):
        parts = key.split(".")
        prefixes = [".".join(parts[:j]) for j in range(len(parts), 1, -1)]
        return any(p in n for p in prefixes for n in notes)

    unexplained = [k for k in nulls if not explained(k)]
    assert not unexplained, ("every null key needs a line in the top-level notes list that names the key or "
                             f"its parent key; unexplained: {unexplained[:25]}")


def test_no_nan_or_infinity(results):
    bad = []

    def walk(node, path):
        if isinstance(node, dict):
            for k, v in node.items():
                walk(v, f"{path}.{k}" if path else str(k))
        elif isinstance(node, list):
            for i, v in enumerate(node):
                walk(v, f"{path}[{i}]")
        elif isinstance(node, float) and not math.isfinite(node):
            bad.append(path)

    walk(results, "")
    assert not bad, f"NaN or infinity (store null with a note instead) at: {bad[:25]}"
